/**
 * The curated "survey" input.
 *
 * Each question lists candidate answers. Every candidate is tied to one or more
 * real English Wikipedia articles. `npm run questions` then asks the Wikimedia
 * Pageviews API how many people actually looked each one up during December and
 * turns that public data into survey points (see scripts/build-questions.ts).
 *
 * - label:    what shows on the board (keep it short)
 * - articles: exact Wikipedia titles whose December pageviews are summed
 * - aliases:  extra accepted spellings (Wikidata aliases are fetched automatically too)
 *
 * Add questions freely - the build script will flag any title it can't find.
 */
export interface CandidateInput {
  label: string;
  articles: string[];
  aliases?: string[];
}
export interface QuestionInput {
  id: string;
  prompt: string;
  /** shorter phrasing used in the Snowball Sprint (fast) round */
  short: string;
  candidates: CandidateInput[];
}

const c = (label: string, articles?: string[] | string, aliases: string[] = []): CandidateInput => ({
  label,
  articles: articles === undefined ? [label] : Array.isArray(articles) ? articles : [articles],
  aliases,
});

